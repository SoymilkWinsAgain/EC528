import argparse
from collections import Counter
import csv
import json
import math
from pathlib import Path

METRICS = {
    'vm_cpu_busy_pct': 'VM CPU busy (%)',
    'vm_memory_used_mib': 'VM memory used (MiB)',
    'total_mbps': 'VM network bandwidth (Mbps; RX + TX)',
    'service_cpu_pct_one_core': 'Python service CPU (% of one core)',
    'service_rss_mib': 'Python service RSS (MiB)',
}


def analyze(root):
    experiment = json.loads((root / 'client/experiment.json').read_text())
    assert experiment['stages'] == [1, 2, 3, 4]
    assert experiment['duration_s'] == 180
    result, samples = [], {}
    for n in range(1, 5):
        summary = json.loads((root / f'client/clients-{n}-summary.json').read_text())
        rows = list(csv.DictReader((root / f'server/metrics-{n}.csv').open()))
        assert len(rows) == 36, f'Stage {n}: incomplete sampling'
        assert abs(float(rows[-1]['elapsed_s']) - 180) < 1
        assert all(int(row['clients']) == n for row in rows)
        assert all(4.5 < float(row['interval_s']) < 5.5 for row in rows)
        assert len({row['service_pid'] for row in rows}) == 1
        assert int(rows[0]['service_pid']) != 0
        event_counts = Counter()
        for file in (root / 'client').glob(f'clients-{n}-worker-*.jsonl'):
            for line in file.read_text().splitlines():
                event = json.loads(line)
                if 'status' in event:
                    event_counts[str(event['status'])] += 1
        assert dict(event_counts) == summary['status_counts'], f'Stage {n}: inconsistent counts'
        record = {
            'clients': n, 'duration_s': 180, 'samples': len(rows),
            'responses_200': event_counts['200'], 'responses_400': event_counts['400'],
            'other_http_responses': sum(v for k, v in event_counts.items() if k not in ('200', '400')),
            'unexpected_exits': summary['unexpected_exits'],
            'requests_without_status': summary['requests_without_status'],
            'client_error_lines': summary['error_lines'],
            'successful_responses_per_s': event_counts['200'] / 180,
            'client_vm_cpu_busy_pct_mean': summary['client_vm_cpu_busy_pct_mean'],
            'client_vm_memory_used_pct_end': summary['client_vm_memory_used_pct_end'],
        }
        weights = [float(row['interval_s']) for row in rows]
        for metric in METRICS:
            values = [float(row[metric]) for row in rows]
            assert all(math.isfinite(v) and v >= 0 for v in values)
            record[metric + '_mean'] = sum(v * w for v, w in zip(values, weights)) / sum(weights)
            record[metric + '_peak'] = max(values)
        result.append(record)
        samples[n] = rows
    return result, samples


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('evidence', type=Path)
    args = parser.parse_args()
    records, samples = analyze(args.evidence)
